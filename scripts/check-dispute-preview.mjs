import assert from 'node:assert/strict';
import {responseDeadline,requestResponse,receiveResponse,recordResolution,completeResolution} from '../dispute-preview-state.mjs';
const initial={status:'Awaiting response',pendingResponders:['Factory'],events:[],files:[]};
assert.equal(receiveResponse(initial,'Brand','Extra details').status,'Awaiting response');
assert.equal(receiveResponse(initial,'Factory','Our response').status,'Ready for TSC review');
const deadline=responseDeadline(2,new Date(2026,10,27,12)); // Friday → Tuesday
assert.equal(new Date(deadline).getDay(),2);
let record=requestResponse(initial,['Brand','Factory'],deadline,'Please supply photos.');
assert.equal(record.status,'Awaiting response');
record=receiveResponse(record,'Brand','Here are our photos');
assert.equal(record.status,'Awaiting response');
assert.deepEqual(record.pendingResponders,['Factory']);
record=receiveResponse(record,'Factory','Here is our evidence');
assert.equal(record.status,'Ready for TSC review');
assert.equal(record.responseDueAt,null);
record=recordResolution(record,'Rework or replacement','Replace affected collars by Friday.','65');
assert.equal(record.status,'Awaiting completion');
assert.equal(receiveResponse(record,'Factory','Work is complete').status,'Awaiting completion');
record=requestResponse(record,['Brand'],deadline,'Confirm the replacement was received.');
assert.equal(record.status,'Awaiting response');
record=receiveResponse(record,'Brand','Received and checked');
assert.equal(record.status,'Awaiting completion');
record=completeResolution(record,'Brand confirmed receipt and quality.');
assert.equal(record.status,'Resolved');
assert.equal(record.events.at(-1).title,'TSC confirmed completion');
assert.throws(()=>completeResolution(initial,'Done'),/Record a resolution/);
assert.equal(initial.events.length,0); // Transitions do not mutate the previous record.
console.log('Dispute preview lifecycle checks pass.');

const {proposeSolution,answerSolution}=await import('../dispute-preview-state.mjs');
let negotiation=proposeSolution(initial,'Brand','Factory',{outcome:'Rework or replacement',details:'Replace affected collars before shipping.',amount:'65'});
assert.equal(negotiation.status,'Awaiting solution response');
assert.throws(()=>answerSolution(negotiation,'Brand','SOL-1','Accepted'),/Only the other party/);
assert.throws(()=>proposeSolution(negotiation,'Brand','Factory',{outcome:'Other',details:'Another offer'}),/Wait for the other party/);
assert.equal(receiveResponse(negotiation,'Factory','We are reviewing this.').status,'Awaiting solution response');
negotiation=proposeSolution(negotiation,'Factory','Brand',{outcome:'Partial refund',details:'Refund the affected units.',amount:'65'});
assert.equal(negotiation.proposals[0].status,'Superseded');
assert.equal(negotiation.proposals[1].to,'Brand');
assert.throws(()=>answerSolution(negotiation,'Brand','SOL-1','Accepted'),/no longer/);
assert.throws(()=>answerSolution(negotiation,'Brand','SOL-2','Declined','  '),/Explain why/);
negotiation=answerSolution(negotiation,'Brand','SOL-2','Declined','We need replacement collars.');
assert.equal(negotiation.status,'Ready for TSC review');
negotiation=proposeSolution(negotiation,'Brand','Factory',{outcome:'Rework or replacement',details:'Replace collars, then provide QC photos.'});
negotiation=answerSolution(negotiation,'Factory','SOL-3','Accepted');
assert.equal(negotiation.status,'Awaiting completion');
assert.equal(negotiation.agreement.acceptedBy,'Factory');
assert.equal(negotiation.proposals.length,3);
assert.throws(()=>answerSolution(negotiation,'Factory','SOL-3','Accepted'),/recorded resolution/);
assert.throws(()=>proposeSolution(negotiation,'Factory','Brand',{outcome:'Other',details:'New offer'}),/recorded resolution/);
negotiation=completeResolution(negotiation,'Brand confirmed the replacement collars.');
assert.equal(negotiation.status,'Resolved');
assert.throws(()=>proposeSolution(initial,'Brand','Factory',{outcome:'Partial refund',details:'Refund',amount:'6000'}),/amount/);
assert.equal(initial.proposals,undefined);
console.log('Dispute solution negotiation checks pass.');
