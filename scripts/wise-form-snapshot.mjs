/**
 * Writes src/shared/wise-form-snapshot.mjs: the form to draw when Wise cannot be
 * reached, so a factory never gets a blank one. Run again with the Wise settings
 * in the environment when Wise's rules change. Never holds a key or a value.
 *
 *   set -a; . ./.env.local; set +a; node scripts/wise-form-snapshot.mjs
 */
import { writeFileSync } from "node:fs";
import { chooseRecipientType, formFromRequirements } from "../api/_wise-requirements-shape.js";

const { WISE_API_BASE: base, WISE_API_TOKEN: token, WISE_PROFILE_ID: profile, WISE_PAYOUT_CURRENCY: currency } = process.env;
const headers = (language) => ({ Authorization: `Bearer ${token}`, "Accept-Minor-Version": "1", "Content-Type": "application/json", "Accept-Language": language });
const quote = await (await fetch(`${base}/v3/profiles/${profile}/quotes`, {
  method: "POST", headers: headers("en"),
  body: JSON.stringify({ sourceCurrency: "USD", targetCurrency: currency, sourceAmount: 1000, payOut: "BANK_TRANSFER" }),
})).json();

async function formIn(language) {
  const url = `${base}/v1/quotes/${quote.id}/account-requirements`;
  const type = chooseRecipientType(await (await fetch(url, { headers: headers(language) })).json());
  const refined = await (await fetch(url, {
    method: "POST", headers: headers(language),
    body: JSON.stringify({ type: type.type, details: { legalType: "BUSINESS", address: { country: "CN" } } }),
  })).json();
  return formFromRequirements(refined.find((item) => item.type === type.type), "CN");
}

const en = await formIn("en");
// English only: the payout screens are one language each (Nov 7).
const snapshot = { ...en, currency, source: "snapshot" };
writeFileSync("src/shared/wise-form-snapshot.mjs", `/** Generated by scripts/wise-form-snapshot.mjs from Wise's account requirements. Don't edit by hand. */
export const WISE_FORM_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)};
`);
console.log(`snapshot: ${snapshot.type}, ${snapshot.fields.map((field) => field.key).join(", ")}`);
